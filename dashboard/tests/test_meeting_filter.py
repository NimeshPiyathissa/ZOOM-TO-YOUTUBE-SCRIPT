LIB = pathlib.Path(__file__).resolve().parents[2] / "scripts" / "lib.sh"


@pytest.mark.skipif(shutil.which("bash") is None or not LIB.exists(), reason="bash or scripts/lib.sh not available")
@pytest.mark.parametrize("w,h,fit,top,bottom,expected", GOLDEN[::3])
def test_matches_bash(w, h, fit, top, bottom, expected, tmp_path):
    body = LIB.read_text().replace("\r", "")
    start = body.index("build_meeting_only_filter() {")
    func = body[start:body.index("\n}\n", start) + 3]
    f = tmp_path / "f.sh"
    f.write_text(func)
    out = subprocess.run(
        ["bash", "-c", f'source "{f.as_posix()}"; build_meeting_only_filter {w} {h} {fit} {top} {bottom}; printf %s "$MEETING_ONLY_FILTER"'],
        capture_output=True, text=True).stdout
    assert out == expected


def _vf_for(monkeypatch, source, size="1920x1080"):
    from app import control
    m = preview.PreviewManager()
    monkeypatch.setattr(control, "read_current_source", lambda: source)
    return asyncio.run(m._meeting_only(size))


def test_preview_crops_only_for_zoom_meeting_only(monkeypatch):
    on = {"SOURCE_TYPE": "zoom", "ZOOM_MEETING_ONLY": "1", "ZOOM_MEETING_ONLY_FIT": "fill"}
    assert _vf_for(monkeypatch, on) == preview.meeting_only_filter(1920, 1080, "fill", 56, 96)
    assert _vf_for(monkeypatch, {**on, "ZOOM_MEETING_ONLY_FIT": "fit"}).startswith("crop=1920:928:0:56,")
    assert _vf_for(monkeypatch, {**on, "ZOOM_MEETING_ONLY": "0"}) == ""          # off = the raw screen, nothing hidden
    assert _vf_for(monkeypatch, {**on, "SOURCE_TYPE": "webpage"}) == ""
    assert _vf_for(monkeypatch, {**on, "SOURCE_TYPE": "edumix"}) == ""
    assert _vf_for(monkeypatch, on, size="garbage") == ""


def test_preview_survives_unreadable_source(monkeypatch):
    from app import control
    def boom():
        raise RuntimeError("sudo failed")
    monkeypatch.setattr(control, "read_current_source", boom)
    assert asyncio.run(preview.PreviewManager()._meeting_only("1280x720")) == ""



